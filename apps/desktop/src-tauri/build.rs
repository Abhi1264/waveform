fn main() {
    // Listing the app's commands makes each one need an explicit permission in
    // capabilities/, instead of being callable by every window by default.
    tauri_build::try_build(tauri_build::Attributes::new().app_manifest(
        tauri_build::AppManifest::new().commands(&[
            "engine_info",
            "list_output_devices",
            "open_default_output",
            "open_output",
            "close_output",
            "play_deck",
            "pause_deck",
            "cue_deck",
            "set_deck_gain",
            "set_crossfader",
            "set_deck_eq",
            "sync_deck",
            "set_deck_loop",
            "deck_analysis",
            "seek_deck",
            "set_deck_pitch",
            "set_hot_cue",
            "jump_hot_cue",
            "beat_jump",
            "set_effect",
            "arm_recording",
            "trigger_sampler",
            "set_input_gain",
            "deck_beats",
            "save_recording",
            "audio_snapshot",
            "watch_audio",
            "search_tracks",
            "import_folder",
            "load_deck_file",
            "create_collection",
            "add_to_collection",
            "collection_tracks",
            "set_track_rating",
            "set_track_metadata",
            "save_mapping",
            "list_mappings",
            "list_folders",
            "tag_track",
            "recent_plays",
        ]),
    ))
    .expect("tauri-build failed");
}
